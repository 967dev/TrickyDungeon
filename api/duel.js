/* Пересыльщик для игры вдвоём. Живёт на Vercel, в саму игру не входит.
   Про игру он не знает НИЧЕГО: получает от одного непрозрачную строку и
   отдаёт второму, кто зашёл в ту же комнату. Правила, карты, здоровье — всё
   это считают сами игроки у себя. Поэтому его можно заменить на что угодно
   другое, переписав один адрес в игре.

   Зависимостей нет ни одной, и это нарочно: ни package.json, ни установки, ни
   сборки. Всё общение с хранилищем — обычными запросами.

   ЧТО УМЕЕТ (всё одним адресом, действие в поле `что`):
     создать  -> {код, зерно}          заводит комнату
     войти    -> {зерно, номер}        вход по коду
     ход      -> {принято, номер}      положить сообщение
     читать   -> {ходы:[...], всего}   забрать сообщения начиная с номера
     жив      -> {}                    отметиться, что не отвалился

   ХРАНИЛИЩЕ БЕЗ ЗАПИСИ НА ДИСК (так на бесплатном тарифе). Если оно
   перезапустится, идущие матчи пропадут. Это терпимо — матч живёт минуты, — но
   игра обязана честно сказать «матч потерян», а не висеть: комнаты нет,
   значит `читать` вернёт `нет комнаты`, и по этому признаку видно, что
   случилось.

   СТО ДЕЙСТВИЙ В СЕКУНДУ — потолок бесплатного хранилища. Поэтому здесь НЕТ
   долгого ожидания на стороне службы: висящий запрос всё это время дёргал бы
   хранилище. Опрашивает игра, и опрашивает с умом — часто, пока ждёт чужой
   ход, и редко в остальное время. */

/* Ключи хранилища берём из того, что подставил Vercel. Названия у него
   разнились от интеграции к интеграции, поэтому принимаем оба и, если нет
   ничего, говорим об этом прямо, а не падаем с невнятной ошибкой. */
/* Имена ищем ПО ОКОНЧАНИЮ, а не по точному совпадению. Vercel приписывает к
   ним название базы: у нас вышло `BumBum_KV_REST_API_URL`, и служба,
   искавшая `KV_REST_API_URL`, не находила ничего. Приставка зависит от того,
   как игрок назвал базу, — угадывать её бессмысленно.

   Ключ берём С ТОЙ ЖЕ приставкой, что и адрес: баз может оказаться несколько
   (у нас одно время висели две), и склеить адрес одной с ключом другой —
   ровно та ошибка, которую потом ищут полдня.

   READ_ONLY отбрасываем явно: он тоже кончается на _TOKEN, но писать им
   нельзя, и отказ пришёл бы только на первой записи, а не при подключении. */
function настройки(){
  const имена = Object.keys(process.env);
  for(const хвостА of ['KV_REST_API_URL','UPSTASH_REDIS_REST_URL']){
    const имяА = имена.find(и => и.endsWith(хвостА));
    if(!имяА) continue;
    const приставка = имяА.slice(0, имяА.length - хвостА.length);
    const хвостК = хвостА.replace('_URL','_TOKEN');
    const имяК = имена.find(и => и === приставка + хвостК && !/READ_ONLY/.test(и));
    if(имяК) return {база:process.env[имяА], ключ:process.env[имяК]};
  }
  return {};
}
const {база:БАЗА, ключ:КЛЮЧ} = настройки();

/* Комната живёт два часа. Матч идёт минуты, но игрок может отойти, а мусор
   сам подметётся: срок ставится на каждой записи. */
const СРОК = 2 * 60 * 60;

/* Откуда пускаем. Игра раздаётся с GitHub Pages, служба живёт на Vercel —
   это разные адреса, и без явного разрешения браузер запрос не выпустит.
   Список закрытый: открывать службу всему интернету незачем. */
const СВОИ = [
  'https://967dev.github.io',
  'https://tricky-dungeon.vercel.app',
  'http://localhost:8842',
  'http://127.0.0.1:8842',
];

async function команда(...части){
  const ответ = await fetch(БАЗА + '/' + части.map(encodeURIComponent).join('/'), {
    headers: { Authorization: 'Bearer ' + КЛЮЧ },
  });
  if(!ответ.ok) throw new Error('хранилище ответило ' + ответ.status);
  return (await ответ.json()).result;
}

const код = () => {
  /* Без похожих знаков: ноль и «O», единица и «I» в пересланной ссылке
     читаются одинаково, а код люди диктуют голосом. */
  const азбука = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  let к = '';
  for(let i=0;i<5;i++) к += азбука[Math.floor(Math.random()*азбука.length)];
  return к;
};

/* Обычный module.exports, а НЕ export default. В корне репозитория нет
   package.json, и без него Node считает .js обычным файлом, а не модулем —
   `export` там просто не разберётся, и выкладка упала бы на ровном месте.
   Заводить package.json ради одного слова не стоит: он же может заставить
   Vercel принять статическую игру за сборочный проект. */
module.exports = async function handler(req, res){
  const откуда = req.headers.origin || '';
  if(СВОИ.includes(откуда)) res.setHeader('Access-Control-Allow-Origin', откуда);
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if(req.method === 'OPTIONS') return res.status(204).end();
  if(req.method !== 'POST') return res.status(405).json({ошибка:'только POST'});

  const тело = typeof req.body === 'string' ? JSON.parse(req.body||'{}') : (req.body||{});
  const что = тело.что;

  /* Что за настройки вообще дошли до службы. ТОЛЬКО ИМЕНА, никаких значений:
     в именах секрета нет, а по ним сразу видно, подключено ли хранилище и под
     какими названиями. Без этого «не подключено» приходится отгадывать.
     Стоит ПОСЛЕ разбора тела — сам на этом и споткнулся, поставив выше. */
  if(что === 'настройки'){
    const имена = Object.keys(process.env)
      .filter(и => /KV|REDIS|UPSTASH/i.test(и)).sort();
    return res.status(200).json({нашлись:имена, всего:имена.length});
  }

  /* Проверка хранилища идёт ПОСЛЕ диагностики, а не до неё. Стояла до — и
     тогда «настройки» до себя не пускала: спросить, чего не хватает, было
     нельзя ровно в том случае, когда это и нужно. */
  if(!БАЗА || !КЛЮЧ)
    return res.status(500).json({ошибка:'хранилище не подключено к проекту',
      подсказка:'спроси действие «настройки» — покажет, какие имена дошли'});
  const комната = String(тело.код||'').toUpperCase();

  try{
    if(что === 'создать'){
      const к = код();
      /* Зерно раздаёт СЛУЖБА, а не создавший комнату: иначе он мог бы
         подобрать себе удобную раздачу, перезаходя, пока не выпадет хорошая. */
      const зерно = Math.floor(Math.random()*0xFFFFFFFF)>>>0;
      /* Имя и герой ездят вместе с комнатой: их надо показать сопернику на
         панели боя. Обрезаем на входе — служба обязана защищаться от того,
         что ей пришлют, а не надеяться на игру. */
      const кто = {имя:String(тело.имя||'').slice(0,16), герой:тело.герой==='m'?'m':'f'};
      await команда('set','к:'+к, JSON.stringify({зерно,второй:0,первыйКто:кто}),
        'EX', String(СРОК));
      return res.status(200).json({код:к, зерно});
    }

    if(!комната) return res.status(400).json({ошибка:'нет кода комнаты'});
    /* Опрос идёт раньше чтения комнаты — ради него всё и затевалось. Пропажу
       комнаты он заметит по пустому списку и по тому, что «читать» ответит
       «нет комнаты»: игра спрашивает его раз в несколько секунд. */
    if(что === 'ждать'){
      const с = Math.max(0, parseInt(тело.с,10)||0);
      const ходы = await команда('lrange','х:'+комната, String(с), '-1');
      return res.status(200).json({ходы:ходы||[], всего:с + (ходы?ходы.length:0)});
    }
    const сырое = await команда('get','к:'+комната);
    if(!сырое) return res.status(404).json({ошибка:'нет комнаты'});
    const данные = JSON.parse(сырое);

    if(что === 'войти'){
      /* Третьего не пускаем. Иначе двое честных увидели бы чужие ходы и
         разошлись бы состояниями, не поняв почему. */
      if(данные.второй) return res.status(409).json({ошибка:'комната занята'});
      данные.второй = 1;
      данные.второйКто = {имя:String(тело.имя||'').slice(0,16), герой:тело.герой==='m'?'m':'f'};
      await команда('set','к:'+комната, JSON.stringify(данные), 'EX', String(СРОК));
      /* Вошедшему сразу отдаём, с кем он играет: он начинает бой немедленно. */
      return res.status(200).json({зерно:данные.зерно, номер:2, соперник:данные.первыйКто||null});
    }

    if(что === 'ход'){
      if(typeof тело.м !== 'string') return res.status(400).json({ошибка:'нет сообщения'});
      /* Сообщение кладём КАК ЕСТЬ, не разбирая: служба не знает про игру, и
         разбор здесь был бы вторым местом, где живут правила. */
      const всего = await команда('rpush','х:'+комната, тело.м);
      await команда('expire','х:'+комната, String(СРОК));
      return res.status(200).json({принято:true, номер:всего});
    }

    if(что === 'читать'){
      const с = Math.max(0, parseInt(тело.с,10)||0);
      const ходы = await команда('lrange','х:'+комната, String(с), '-1');
      /* Создавший узнаёт соперника отсюда: он ждёт на этом же опросе. */
      return res.status(200).json({ходы:ходы||[], всего:с + (ходы?ходы.length:0),
        второй:данные.второй?1:0, соперник:данные.второйКто||null});
    }
    if(что === 'жив'){
      /* Отметка «я на связи». По ней вторая сторона понимает, что соперник не
         отвалился: решение автора — ждать минуту, потом засчитывать победу. */
      await команда('set','ж:'+комната+':'+(тело.номер===2?2:1), String(Date.now()), 'EX', '300');
      const а = await команда('get','ж:'+комната+':1');
      const б = await команда('get','ж:'+комната+':2');
      return res.status(200).json({первый:+(а||0), второй:+(б||0), сейчас:Date.now()});
    }

    return res.status(400).json({ошибка:'неизвестное действие'});
  }catch(e){
    return res.status(500).json({ошибка:String(e && e.message || e)});
  }
}
