/* 15-duel.js — игра вдвоём: связь с пересыльщиком и состояние матча.

   Часть скрипта, разрезанного из одного файла. ПОРЯДОК ПОДКЛЮЧЕНИЯ В
   index.html ЗНАЧИМ: подключается ПЕРЕД 16-boot.js, потому что запуск зовёт
   отсюда восстановление матча.

   ЭКРАНА ЭТОТ ФАЙЛ НЕ КАСАЕТСЯ — как и правила. Он только разговаривает со
   службой и держит состояние матча; рисует всё подача, по обратным вызовам
   из Д.когда. Разрез тот же, что между правилами и показом, и по той же
   причине: сеть надо будет проверять без экрана.

   Служба про игру не знает ничего: получает строку и отдаёт второму. Правила
   считают оба у себя, из одного зерна. */

/* Адрес службы. Игра раздаётся с GitHub Pages, служба живёт на Vercel — это
   разные адреса, и в самой службе список разрешённых прописан отдельно.
   Заменить пересыльщика — это поменять здесь одну строку. */
const ДУЭЛЬ_АДРЕС='https://tricky-dungeon.vercel.app/api/duel';

/* Как часто спрашиваем «что нового». Опрос — самое частое обращение к службе,
   а на бесплатном хранилище полмиллиона обращений в месяц. Поэтому спрашиваем
   ЧАСТО, только пока ждём чужой ход, и редко в остальное время: двое молча
   сидящих в лобби не должны съедать столько же, сколько играющие. */
const ОПРОС_ЖДУ=900, ОПРОС_ТИХО=3000;
/* Полным запросом (он дороже, зато замечает пропажу комнаты) — изредка. */
const ОПРОС_ПОЛНЫЙ=6000;
/* Решения автора: 30 секунд на ход, минута ожидания отвалившегося. */
const ДУЭЛЬ_ХОД_МС=30000, ДУЭЛЬ_ЖДАТЬ_МС=60000;
/* Столько же — на замену стартовой руки. Не отдельное число нарочно: это тот
   же вопрос «сколько человек имеет право думать, пока второй ждёт», и второй
   ответ на него пришлось бы объяснять. */
const ДУЭЛЬ_МУЛЛИГАН_МС=ДУЭЛЬ_ХОД_МС;

const Д={
  вкл:false,       /* идёт ли матч */
  соперник:null,   /* {имя,герой} — с кем играем; приходит от службы */
  код:'',          /* код комнаты */
  зерно:0,
  первый:false,    /* создал комнату — значит ходит первым */
  прочитано:0,     /* сколько чужих сообщений уже забрали */
  связь:0,         /* когда последний раз слышали соперника */
  таймер:0,        /* когда истекает время текущего хода */
  /* Замена стартовой руки: кто уже управился. Два флага, а не один счётчик, —
     сообщение «готов» может прийти дважды (опрос перечитывает список только
     вперёд, но перестраховка тут дешевле разбирательства). */
  готовЯ:false,готовОн:false,началось:false,
  ждуС:0,          /* с какого момента жду чужой готовности */
  когда:{},        /* обратные вызовы для подачи */
  _опрос:null,_полный:null,
};

/* Как меня зовут для соперника. В Телеграме — тамошнее имя, вне его — то,
   что игрок придумал при первом заходе. Если нет ни того ни другого,
   подписываем нейтрально: пустая подпись под портретом выглядит поломкой. */
function дЯКто(){
  const тг=(PF&&PF.имяДляСоперника)?PF.имяДляСоперника():'';
  return {имя:(тг||S.name||'СОПЕРНИК').slice(0,16), герой:S.hero==='m'?'m':'f'};
}

async function дспрос(что,ещё){
  const о=await fetch(ДУЭЛЬ_АДРЕС,{method:'POST',
    headers:{'Content-Type':'application/json'},
    body:JSON.stringify(Object.assign({что},ещё||{}))});
  const т=await о.text();
  let д={};try{д=JSON.parse(т)}catch(e){д={ошибка:'служба ответила не по делу'}}
  if(!о.ok&&!д.ошибка)д.ошибка='служба ответила '+о.status;
  return д;
}

/* Создать комнату. Зерно даёт СЛУЖБА — иначе создавший мог бы перезаходить,
   пока не выпадет удобная раздача. */
async function дСоздать(){
  const о=await дспрос('создать',дЯКто());
  if(о.ошибка)return о;
  Object.assign(Д,{вкл:true,код:о.код,зерно:о.зерно,первый:true,прочитано:0,
    связь:Date.now(),таймер:0,соперник:null,
    готовЯ:false,готовОн:false,началось:false,ждуС:0});
  дЗапуститьОпрос();
  return о;
}

async function дВойти(код){
  const о=await дспрос('войти',Object.assign({код},дЯКто()));
  if(о.ошибка)return о;
  Object.assign(Д,{вкл:true,код:String(код).toUpperCase(),зерно:о.зерно,
    первый:false,прочитано:0,связь:Date.now(),таймер:0,соперник:о.соперник||null,
    готовЯ:false,готовОн:false,началось:false,ждуС:0});
  дЗапуститьОпрос();
  return о;
}

/* Объявить свой ход. Сообщение уходит КАК ЕСТЬ: служба его не разбирает.
   Ошибку сети наверх не глотаем — подача обязана сказать игроку, что ход не
   доехал, иначе он будет думать, что сходил. */
async function дПослать(м){
  if(!Д.вкл)return{ошибка:'матча нет'};
  /* К каждому сообщению приписываем, КТО его послал. Без этого не обойтись:
     пересыльщик держит один общий список на комнату и отдаёт всё подряд, а
     значит и твои собственные ходы возвращаются к тебе же. Первый прогон на
     двух вкладках так и сломался — каждый применял свой «конец хода» дважды,
     счётчики ходов разъехались, и оба оказались в своей фазе одновременно.
     Пересыльщик при этом остаётся тупым: разбирать сообщения он по-прежнему
     не должен. */
  const о=await дспрос('ход',{код:Д.код,м:JSON.stringify(Object.assign({от:дЯ()},м))});
  if(!о.ошибка)Д.связь=Date.now();
  return о;
}
/* Кто я в этой комнате: создавший — первый, вошедший — второй. */
const дЯ=()=>Д.первый?1:2;

/* Ссылка-приглашение. Отдельной функцией, потому что зовут её из двух мест —
   с экрана ожидания и из кнопки «позвать ещё раз». */
function дСсылка(){
  return location.origin+location.pathname+'?матч='+Д.код;
}
/* Код из адреса — по нему игра поймёт, что её открыли по приглашению. */
function дКодИзАдреса(){
  const м=new URLSearchParams(location.search).get('матч');
  return м?String(м).toUpperCase().replace(/[^A-Z0-9]/g,'').slice(0,5):'';
}

function дЗапуститьОпрос(){
  дОстановитьОпрос();
  Д._опрос=setInterval(дТик,ОПРОС_ЖДУ);
  Д._полный=setInterval(дТикПолный,ОПРОС_ПОЛНЫЙ);
}
function дОстановитьОпрос(){
  if(Д._опрос)clearInterval(Д._опрос);
  if(Д._полный)clearInterval(Д._полный);
  Д._опрос=Д._полный=null;
}
function дЗакрыть(){
  дОстановитьОпрос();
  Д.вкл=false;Д.код='';Д.прочитано=0;Д.таймер=0;
  Д.готовЯ=Д.готовОн=Д.началось=false;Д.ждуС=0;
}

/* Быстрый опрос: только новые сообщения, без чтения записи комнаты. */
let дЗанят=false;
async function дТик(){
  if(!Д.вкл||дЗанят)return;
  дЗанят=true;
  try{
    const о=await дспрос('ждать',{код:Д.код,с:Д.прочитано});
    if(о.ошибка)return;
    if(о.ходы&&о.ходы.length){
      Д.прочитано=о.всего;Д.связь=Date.now();
      for(const строка of о.ходы){
        let м=null;try{м=JSON.parse(строка)}catch(e){continue}
        /* СВОИ ходы пропускаем: список общий, и они возвращаются к нам же.
           Применить свой ход второй раз — значит сходить дважды. */
        if(м.от===дЯ())continue;
        /* «ГОТОВ» РАЗБИРАЕТСЯ ЗДЕСЬ, а не в подаче боя, и это не вкусовщина.
           Второй игрок заводит матч сразу по входу, а первый узнаёт о нём
           только полным опросом — раз в шесть секунд. Всё это время у первого
           обработчик хода ещё не подключён, и чужая готовность, разобранная
           подачей, была бы прочитана и выброшена: `Д.прочитано` ушло вперёд,
           а сообщения больше нет. Дальше первый ждал бы вечно.
           Флаг — состояние связи, а не показ, и живёт он тут. */
        if(м.т==='готов'){
          Д.готовОн=true;
          if(Д.когда.готов)Д.когда.готов();
          continue;
        }
        if(Д.когда.ход)Д.когда.ход(м);
      }
    }
  }finally{дЗанят=false}
}

/* Полный опрос: замечает, что второй зашёл, и что комната пропала.
   Пропажа комнаты — не выдумка: хранилище на бесплатном тарифе без записи на
   диск, и при его перезапуске идущие матчи исчезают. Игра обязана сказать об
   этом прямо, а не висеть в ожидании хода, который никогда не придёт. */
async function дТикПолный(){
  if(!Д.вкл)return;
  const о=await дспрос('читать',{код:Д.код,с:Д.прочитано});
  if(о.ошибка==='нет комнаты'){
    if(Д.когда.потерян)Д.когда.потерян();
    дЗакрыть();return;
  }
  if(о.ошибка)return;
  if(о.соперник)Д.соперник=о.соперник;
  if(о.второй&&Д.когда.вошёл)Д.когда.вошёл();
  await дспрос('жив',{код:Д.код,номер:Д.первый?1:2}).then(ж=>{
    if(ж&&!ж.ошибка){
      const чужой=Д.первый?ж.второй:ж.первый;
      if(чужой){
        const молчит=ж.сейчас-чужой;
        if(молчит>ДУЭЛЬ_ЖДАТЬ_МС&&Д.когда.пропал)Д.когда.пропал(молчит);
      }
    }
  }).catch(()=>{});
}

/* ================= ЭКРАН МАТЧА =================
   Ниже — единственное место в этом файле, которое трогает разметку. Держу его
   здесь, а не в подаче боя, потому что это экран ЛОББИ, а не боя: он живёт до
   первого хода и после него не показывается.

   Экран один на все состояния (выбор, ожидание, ошибка). Состояний мало, а
   отдельными экранами их пришлось бы синхронно прятать друг от друга. */
let дСостояние='выбор';     /* выбор | жду | вошёл | ошибка */
let дОшибка='';

