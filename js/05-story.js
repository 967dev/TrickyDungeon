/* Когда какая сцена играется. Ключ — этап, значение — что показать ДО боя и
   что ПОСЛЕ победы. Держим таблицей, а не проверками по коду: появится сцена в
   акте 2 — это одна строка, и обе двери (плитка рейда и кнопки итогов) её
   подхватят сами. */
const SCENE_AT={
  before:{10:['final']},
  after :{7:['cafe','morning'], 10:['win','dark']}
};
/* Что из списка ещё не показано. Флаг на сцену, а не общий: сцен пять, и одна
   отметка «сюжет видел» похоронила бы четыре остальных. */
function сценыДолги(список){
  return (список||[]).filter(id=>SCENES[id]&&!(S.scenes&&S.scenes[id]));
}
function сценыЭтапа(когда,si){return сценыДолги((SCENE_AT[когда]||{})[si])}
/* Показать очередь сцен подряд, потом продолжить. Возвращает true, если
   что-то показывается: вызывающему тогда своё дело откладывать. */
function сценыПодряд(список,after){
  const очередь=сценыДолги(список);
  if(!очередь.length)return false;
  const шаг=()=>{
    const id=очередь.shift();
    if(!id)return after&&after();
    vnLoad(SCENES[id].intro,900,()=>startScene(id,шаг));
  };
  шаг();
  return true;
}

