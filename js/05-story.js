function vnNext(){vnI++;if(vnI>=vnCur().beats.length)vnDone();else vnShow()}
function vnDone(){
  /* Вступление отмечается своим флагом (на нём стоит кнопка «пересмотреть» в
     табло), катсцены — каждая своей записью. Общая отметка «сюжет видел» тут
     не годится: сцен пять, и первая же похоронила бы остальные. */
  const sc=vnScene;
  if(sc&&sc.id){S.scenes=S.scenes||{};S.scenes[sc.id]=1}
  else S.story=1;
  save();
  vnScene=null;
  const after=vnAfter;vnAfter=null;
  if(after)after();else go('menu');
}
function startStory(after){
  vnScene=null;
  vnAfter=after||null;vnI=0;vnArt=0;
  go('story');
  vnShow();
}
/* Катсцена по имени. Отдельный вход, а не флаг у startStory: вступление и
   катсцены различаются тем, ЧЕЙ это сюжет, и путать их нельзя. */
function startScene(id,after){
  const sc=SCENES[id];if(!sc){if(after)after();return}
  vnScene=sc;
  vnAfter=after||null;vnI=0;vnArt=0;
  go('story');
  vnShow();
}
/* Короткая заставка-пересадка. cb вызывается на пике затемнения, поэтому
   смена экрана не видна игроку. */
function vnLoad(text,ms,cb){
  const el=document.createElement('div');el.className='vnLoad';
  el.innerHTML=`<div class="vlT">${text}</div><div class="vlBar"><i></i></div>`;
  document.body.appendChild(el);
  setTimeout(()=>{
    try{cb&&cb()}catch(e){}
    el.classList.add('out');
    setTimeout(()=>el.remove(),320);
  },ms||1000);
}
