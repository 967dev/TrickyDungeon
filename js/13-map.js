/* ================= узлы ================= */
const мСцена  = () => $('#mapScene');
const мГород  = () => $('#mapCity');

/* Текущее состояние ПОКАЗА. Отдельно от S нарочно: S.mapAct — что игрок уже
   видел, а МАП.актов — что нарисовано сейчас. Они расходятся ровно на время
   проигрывания открытия. */
const МАП={актов:1, выбран:null, собрано:'', ждать:true};
/* Активный слой тумана показывает текущее состояние, спящий ждёт с нулевой
   прозрачностью. Открытие — перекрёстное затухание, после которого они
   меняются ролями. Так ни один дым нигде не перезапускается. */
let мАктивный=null, мСпящий=null;

function мУзкий(){ return innerWidth<=700 }
/* Мобильная раскладка — своя, а не пересчёт широкой. */
const мМесто = а => мУзкий() ? Object.assign({},а,а.узк) : а;

/* ================= что где ================= */
/* Бои района. По полю акт, а не по счёту: вставка «Тренировки» нулевым этапом
   один раз уже сдвинула все индексы. */
function боиАкта(n){
  const из=[];
  STAGES.forEach((st,i)=>{ if(st.акт===n)из.push(i) });
  return из;
}
/* Рейды района — бои БЕЗ обучения. Обучение стоит в акте, потому что оно
   первое, что игрок делает, но считать его боем акта нельзя: оно
   необязательное, и по нему нельзя решать, зачищен район или нет. Иначе игрок,
   пропустивший тренировку, не откроет следующий район никогда. */
const рейдыАкта = n => боиАкта(n).filter(i=>!STAGES[i].tutorial);
/* Район готов к показу только когда за ним что-то есть. Показать силуэт места,
   которого не существует, значит соврать. */
const мЕсть = а => !!(а.имя && а.арт && рейдыАкта(а.акт).length);

/* Сколько районов открыто по прогрессу. Район открывается, когда предыдущий
   зачищен ЦЕЛИКОМ. */
function мАктовОткрыто(){
  let n=1;
  for(const а of АКТЫ){
    const бои=рейдыАкта(а.акт);
    if(!бои.length)break;                    /* акта ещё нет — дальше не идём */
    if(!бои.every(i=>S.done[i]))break;
    n=а.акт+1;
  }
  return Math.min(n,ФИНАЛ,АКТЫ.length);
}

/* Всё доступное содержимое пройдено. Считаем по актам ДО границы выпуска и
   только по тем, у кого бои есть: акт 2 назван, но пока пуст, и требовать
   зачистки того, чего нет, значит не показать финал никогда. */
function мВсёПройдено(){
  let былоЧто=false;
  for(const а of АКТЫ){
    if(а.акт>ФИНАЛ)break;
    const р=рейдыАкта(а.акт);
    if(!р.length)continue;
    былоЧто=true;
    if(!р.every(i=>S.done[i]))return false;
  }
  return былоЧто;
}
/* Последний акт, за которым что-то есть. Его табло и показывает финал. */
function мПоследнийАкт(){
  let n=1;
  for(const а of АКТЫ){ if(а.акт>ФИНАЛ)break; if(рейдыАкта(а.акт).length)n=а.акт }
  return n;
}

/* Состояние района при заданном числе открытых. Число — параметр, а не
   С.актов, потому что при открытии надо спросить «а как было ДО» — на этом
   держится уходящая копия тумана. */
function мСост(а,актов){
  /* Граница выпуска — раньше всех прочих правил. Без неё «один шаг вперёд
     виден всегда» показал бы силуэт района, которого в этом выпуске нет. */
  if(а.акт>ФИНАЛ)return 'fog';
  if(МАП.ждать&&!мЕсть(а))return 'fog';
  if(а.акт<актов)return 'done';
  if(а.акт===актов)return 'open';
  if(а.акт===актов+1)return 'next';           /* один шаг вперёд виден всегда */
  return 'fog';
}

/* ================= районы ================= */
/* Районы ПЕРЕИСПОЛЬЗУЮТСЯ. Пересоздание узла рождает заново все его переходы,
   то есть новое состояние встаёт щелчком — и открытие района читается как
   дорисовка, а не как раскрытие. */
function мНарисоватьРайоны(){
  const карта=мГород();
  for(const а of АКТЫ){
    const сост=мСост(а,МАП.актов);
    let el=карта.querySelector('.mapDist[data-act="'+а.акт+'"]');
    if(!el){
      el=document.createElement('div');
      el.dataset.act=а.акт;
      el.style.setProperty('--блоб',БЛОБЫ[а.блоб]);
      el.innerHTML=
        '<div class="mdEdge"></div>'+
        '<div class="mdArt">'+
          (а.арт?'<img src="'+а.арт+'" alt="" draggable="false">':'')+'</div>'+
        '<div class="mdTag">АКТ '+а.акт+'</div>'+
        /* На районе стоит НАЗВАНИЕ АКТА, а не имя места: в табло того же
           района написано «ИЗ ГРЯЗИ В КАРТЫ!», и разные подписи у одного и
           того же читались как два разных места. Имя места ушло подписью
           ниже — оно там и к месту. */
        '<div class="mdName">'+(а.титул||а.имя||'—')+'</div>'+
        (а.под?'<div class="mdSub">'+а.под+'</div>':'')+
        '<div class="mdLock"><svg viewBox="0 0 24 24">'+
          '<rect x="5" y="11" width="14" height="10"/><path d="M8 11V8a4 4 0 0 1 8 0v3"/></svg></div>';
      карта.appendChild(el);
    }
    el.className='mapDist '+сост+(мЕсть(а)?'':' empty');
    const м=мМесто(а);
    el.style.setProperty('--ш',м.ш);
    el.style.left=м.x+'%';
    el.style.top =м.y+'%';
    el.onclick=(сост==='open'||сост==='done')?(()=>мОткрытьПанель(а)):null;
  }
}

/* ================= дороги =================
   Концы дороги — от КРАЯ к краю, а не от центра к центру: дорога, выходящая из
   середины района, читается как воткнутая в него булавка.
   Район считаем эллипсом по его коробке: контур рваный, но вписанный эллипс от
   него почти не отличается, а точка выхода тогда берётся формулой, без обхода
   полигона.
   Вынесено отдельной функцией потому, что этим же путём идёт трасса открытия:
   ей нельзя разойтись с пунктиром ни на пиксель. */
function мКонцы(ма,мб,W,H){
  const ax=ма.x/100*W, ay=ма.y/100*H;
  const bx=мб.x/100*W, by=мб.y/100*H;
  const кр=(м,dx,dy)=>{
    const пол=м.ш.replace('%','')/100*W/2;    /* полуось по ширине */
    const a2=пол, b2=пол/1.35;                /* и по высоте: коробка 1.35:1 */
    const t=1/Math.hypot(dx/a2,dy/b2);
    return [dx*t,dy*t];
  };
  const dx=bx-ax, dy=by-ay;
  const [ox,oy]=кр(ма,dx,dy);
  const [ix,iy]=кр(мб,-dx,-dy);
  const зазор=7;                              /* чтобы пунктир не лип к обводке */
  const дл=Math.hypot(dx,dy)||1;
  return [ax+ox+dx/дл*зазор, ay+oy+dy/дл*зазор,
          bx+ix-dx/дл*зазор, by+iy-dy/дл*зазор];
}
/* Небольшой изгиб в сторону: прямая между районами читается как линейка, а не
   как дорога. */
function мДуга(нx,нy,кx,кy){
  const cx=(нx+кx)/2+(кy-нy)*0.14, cy=(нy+кy)/2+(нx-кx)*0.14;
  return 'M'+нx.toFixed(1)+' '+нy.toFixed(1)+
         ' Q'+cx.toFixed(1)+' '+cy.toFixed(1)+' '+кx.toFixed(1)+' '+кy.toFixed(1);
}
/* Дороги ПЕРЕИСПОЛЬЗУЮТСЯ по той же причине, что районы: с пересозданием узла
   бегущий пунктир прыгает в начало ровно в тот кадр, когда открывается район.
   Считаем в пикселях коробки, а не в процентах: у процентного viewBox с
   preserveAspectRatio="none" штрих и точки расплющивает по одной оси, и
   аккуратный пунктир превращается в кляксы. */
function мНарисоватьДороги(){
  const карта=мГород(), путь=$('#mapRoads');
  const W=карта.clientWidth, H=карта.clientHeight;
  путь.setAttribute('viewBox','0 0 '+W+' '+H);
  const НС='http://www.w3.org/2000/svg';
  let n=0;
  for(let i=0;i<АКТЫ.length-1;i++){
    const a=АКТЫ[i], b=АКТЫ[i+1];
    const сa=мСост(a,МАП.актов), сb=мСост(b,МАП.актов);
    /* Из тумана дорог не бывает: дошли до неоткрытого начала — дальше не идём. */
    if(сa!=='done'&&сa!=='open')break;
    const [нx,нy,кx,кy]=мКонцы(мМесто(a),мМесто(b),W,H);
    /* Глухая — по СОСТОЯНИЮ конца, а не по его номеру. По номеру выходило, что
       после зачистки акта 1 дорога в акт 2 становилась живой и жёлтой, хотя
       сам акт 2 лежит в тумане: бегущий пунктир вёл в никуда. */
    const глухой=(сb!=='done'&&сb!=='open');
    let л=путь.children[n*2], т=путь.children[n*2+1];
    if(!л){л=document.createElementNS(НС,'path');л.setAttribute('fill','none');путь.appendChild(л)}
    if(!т){т=document.createElementNS(НС,'circle');путь.appendChild(т)}
    л.setAttribute('d',мДуга(нx,нy,кx,кy));
    т.setAttribute('cx',кx.toFixed(1)); т.setAttribute('cy',кy.toFixed(1));
    т.setAttribute('r',4.5);
    л.classList.toggle('dead',глухой);
    т.classList.toggle('dead',глухой);
    л.style.display=т.style.display='';
    n++;
  }
  /* Лишние прячем, а не удаляем: удаление — это снова пересоздание при
     следующем показе, то есть снова прыжок анимации. */
  for(let k=n*2;k<путь.children.length;k++)путь.children[k].style.display='none';
}

/* ================= туман =================
   Слой собирается ОДИН РАЗ, а при изменении прогресса меняются только прогалы
   внутри маски. С полной перерисовкой вместе с разметкой пересоздаются клубы,
   и их анимация прыгает в начало: при открытии района дым будто заново
   приходит в движение. Именно это и было заметно.

   Прогал — клякса с размытым краем. Через это пришлось пройти трижды: один
   эллипс с мягким сходом давал серый ОВАЛЬНЫЙ ореол, потому что муть кончалась
   по правильной кривой. Пять пятен вышли хуже — в маске они красят друг друга
   по порядку, и белый край одного стирает чёрное ядро соседнего. Объединить их
   mix-blend-mode:darken можно, но маску тогда пересчитывает каждый кадр, и
   страница встаёт. Работает третье: фигура сама неровная, а край ей даёт одно
   размытие; сплошной чёрный склеивается без всяких блендов. */
const мДрожь=(i,k)=>{
  const s=Math.sin(i*12.9898+k*78.233)*43758.5453;
  return s-Math.floor(s);                     /* 0..1, но всегда одно и то же */
};
function мКлякса(cx,cy,r,i){
  const n=13;
  let d='';
  for(let k=0;k<n;k++){
    const a=k/n*Math.PI*2;
    const рад=r*(0.80+0.42*мДрожь(i,k));
    d+=(k?'L':'M')+(cx+Math.cos(a)*рад).toFixed(0)+' '+(cy+Math.sin(a)*рад*0.84).toFixed(0)+' ';
  }
  return '<path d="'+d+'Z"/>';
}
/* Пелена — копия текстуры, растянутая шире карты. Шире нарочно: она ещё и
   ездит, и на краю не должно проступать её собственное чёрное поле. */
function мПелена(W,H,мш,dx,dy,a){
  const ш=W*мш, в=ш;                          /* текстура квадратная */
  return '<image class="mfVeil" href="art/fog.webp" preserveAspectRatio="none"'+
    ' x="'+((W-ш)/2+W*dx).toFixed(0)+'" y="'+((H-в)/2+H*dy).toFixed(0)+
    '" width="'+ш.toFixed(0)+'" height="'+в.toFixed(0)+'" opacity="'+a+'"/>';
}
/* Бледь: насколько слой тумана выходит за карту с каждой стороны. Совпадает с
   left/top/width/height у .mapFog в стилях — менять надо оба места. */
const МБЛЕДЬ=0.35;
function мМера(){
  const карта=мГород();
  const W=карта.clientWidth, H=карта.clientHeight;
  return {W,H,ШФ:W*(1+2*МБЛЕДЬ),ВФ:H*(1+2*МБЛЕДЬ),оx:W*МБЛЕДЬ,оy:H*МБЛЕДЬ};
}
/* Каркас слоя: маска с пустыми группами прогалов, тело и три ползущих пелены. */
function мСобратьТуман(цель){
  const {W,ШФ,ВФ}=мМера();
  const ид=цель.id;
  цель.setAttribute('viewBox','0 0 '+ШФ+' '+ВФ);
  /* id маски и фильтра — СВОИ у каждого слоя. Оба объявляли одинаковый id, а
     при одинаковых id ссылка url(#...) находит первый по документу: копия
     прежнего тумана брала маску нового слоя и показывала уже расчищенный
     район. Рассеиваться было нечему, и открытие выглядело мгновенным. */
  цель.innerHTML=
    '<defs>'+
      '<filter id="mfBlur-'+ид+'" x="-30%" y="-30%" width="160%" height="160%">'+
        '<feGaussianBlur stdDeviation="'+(W*0.035).toFixed(0)+'"/></filter>'+
      '<mask id="mfHoles-'+ид+'" maskUnits="userSpaceOnUse" x="0" y="0" width="'+ШФ+'" height="'+ВФ+'">'+
        '<rect width="'+ШФ+'" height="'+ВФ+'" fill="#fff"/>'+
        '<g class="mfThin" fill="#3a3a3a" filter="url(#mfBlur-'+ид+')"></g>'+
        '<g class="mfFull" fill="#000"    filter="url(#mfBlur-'+ид+')"></g>'+
      '</mask>'+
    '</defs>'+
    '<g mask="url(#mfHoles-'+ид+')">'+
      '<rect width="'+ШФ+'" height="'+ВФ+'" fill="#08080d" opacity=".97"/>'+
      '<g class="mfC1">'+мПелена(ШФ,ВФ,1.5,-.06, .12,.52)+'</g>'+
      '<g class="mfC2">'+мПелена(ШФ,ВФ,1.15, .10, .22,.36)+'</g>'+
      '<g class="mfC3">'+мПелена(ШФ,ВФ,1.9,  .02,-.02,.24)+'</g>'+
    '</g>';
}
/* Только прогалы. Пелены не трогаются, поэтому их движение не рвётся.

   Расчищается ДВА рода мест: сами районы и дороги между ними. Одним пятном на
   район не выходит: чтобы оно заодно освобождало дороги, радиус приходится
   брать вдвое больше самого района — и тогда пятно открытого акта достаёт до
   следующего ЧЕРЕЗ ОДИН и показывает его сквозь туман. */
function мОбновитьПрогалы(цель,актов){
  const {W,H,оx,оy}=мМера();
  /* Координаты района — в системе СЛОЯ, а он сдвинут на бледь. */
  const где=а=>{const м=мМесто(а);
    return [оx+м.x/100*W, оy+м.y/100*H, м.ш.replace('%','')/100*W]};
  let полные='', редкие='';
  АКТЫ.forEach((а,i)=>{
    const с=мСост(а,актов);
    if(с==='fog')return;
    const [cx,cy,r]=где(а);
    /* Пройденное и открытое расчищаем совсем, а следующий район оставляем ПОД
       РЕДЕЮЩЕЙ мутью: он должен угадываться, а не открываться. */
    if(с==='next')редкие+=мКлякса(cx,cy,r*0.50,i);
    else          полные+=мКлякса(cx,cy,r*0.62,i);
  });
  /* Дорога расчищается на ту же глубину, что и район на её конце: до открытого
     — насквозь, до следующего — в редеющую муть. Иначе дорога между двумя
     открытыми районами уходила бы в туман на полпути. */
  const кисть=(W*0.035).toFixed(0);
  for(let i=0;i<АКТЫ.length-1;i++){
    const сa=мСост(АКТЫ[i],актов), сb=мСост(АКТЫ[i+1],актов);
    if(сa==='fog'||сb==='fog')break;
    const [ax,ay]=где(АКТЫ[i]), [bx,by]=где(АКТЫ[i+1]);
    const цвет=(сb==='next')?'#3a3a3a':'#000';
    const d='<path d="'+мДуга(ax,ay,bx,by)+'" fill="none" stroke="'+цвет+
      '" stroke-width="'+кисть+'" stroke-linecap="round"/>';
    if(сb==='next')редкие+=d; else полные+=d;
  }
  const п=цель.querySelector('.mfFull'), р=цель.querySelector('.mfThin');
  if(п)п.innerHTML=полные;
  if(р)р.innerHTML=редкие;
}

/* ================= открытие района =================
   То, ради чего карта и нужна: игрок вернулся с последнего боя акта, и город
   при нём растёт. Сперва прочерчивается дорога — она ведёт взгляд туда, куда
   смотреть, — и в конце её сходит туман. Порядок важен: если гасить туман
   сразу, открытие происходит на периферии зрения и его можно не заметить.

   Пока в игре один акт, играть тут нечего: следующий район пуст, и открытие
   на нём не запускается (см. мЕсть). Механизм лежит готовым — акт 2 включится
   строчкой в АКТЫ и полем «акт» у его боёв. Гонять его до тех пор можно на
   стенде map-lab.html. */
let мИдёт=false;
/* Метка показа. Уборка отложена на три секунды, и без метки таймер прошлого
   открытия успевал стереть слой уже НАЧАВШЕГОСЯ нового. */
let мПоказ=0;
/* Разгон и возврат клубов. updatePlaybackRate меняет скорость У ИДУЩЕЙ
   анимации, не сбрасывая её время. Через CSS нельзя: смена длительности
   перезапускает анимацию с нуля, пелена скачком уходит в начальную позицию, а
   потом плавно едет обратно — это и было видно как рывок вправо со сползанием
   влево. */
function мПорыв(слой,скорость){
  слой.querySelectorAll('.mfC1,.mfC2,.mfC3').forEach(g=>
    g.getAnimations().forEach(a=>{try{a.updatePlaybackRate(скорость)}catch(e){}}));
}

async function мСыгратьОткрытие(){
  const было=МАП.актов;
  if(было>=АКТЫ.length)return false;
  const след=АКТЫ[было];                      /* тот, что откроется */
  if(МАП.ждать&&!мЕсть(след))return false;
  мИдёт=true;
  const мой=++мПоказ;
  const карта=мГород(), трасса=$('#mapTrace');

  /* --- 1. трасса от пройденного района к новому --- */
  const W=карта.clientWidth, H=карта.clientHeight;
  const [нx,нy,кx,кy]=мКонцы(мМесто(АКТЫ[было-1]),мМесто(след),W,H);
  трасса.setAttribute('viewBox','0 0 '+W+' '+H);
  const тр=document.createElementNS('http://www.w3.org/2000/svg','path');
  тр.setAttribute('d',мДуга(нx,нy,кx,кy));
  трасса.appendChild(тр);
  const L=тр.getTotalLength();
  тр.style.strokeDasharray=L;
  тр.style.strokeDashoffset=L;
  await тр.animate([{strokeDashoffset:L},{strokeDashoffset:0}],
    {duration:820,easing:'cubic-bezier(.4,0,.3,1)',fill:'forwards'}).finished.catch(()=>{});

  /* --- 2. туман сходит --- */
  /* Прогалы нового состояния кладём в СПЯЩИЙ слой и показываем его ПОД
     уходящим. Ни один слой не пересобирается, поэтому клубы у обоих продолжают
     ползти с того места, где были. */
  const уходит=мАктивный, приходит=мСпящий;
  мОбновитьПрогалы(приходит,было+1);
  приходит.classList.add('on');

  МАП.актов=было+1;
  /* Роли меняем сразу: отрисовка состояния должна идти уже в новый слой. */
  мАктивный=приходит; мСпящий=уходит;
  мНарисоватьРайоны();
  мНарисоватьДороги();

  /* Муть расходится ОТ нового района, а не от середины экрана. */
  const м2=мМесто(след);
  уходит.style.transformOrigin=м2.x+'% '+м2.y+'%';
  уходит.classList.add('gone');
  мПорыв(уходит,2.6);                         /* ветер, без перезапуска */

  await new Promise(r=>setTimeout(r,3200));
  if(мой!==мПоказ){мИдёт=false;return true}   /* показ уже сменился */
  уходит.classList.remove('gone','on');
  уходит.style.transformOrigin='';
  мПорыв(уходит,1);                           /* слой уходит в запас */
  /* Трассу не срезаем, а гасим: под ней уже лежит обычный пунктир, и резкая
     подмена читается как рывок. */
  await тр.animate([{opacity:.95},{opacity:0}],{duration:420,fill:'forwards'})
    .finished.catch(()=>{});
  тр.remove();
  мИдёт=false;
  return true;
}
/* Догнать прогресс. Обычно это один район, но сейв мог прийти из облака сразу
   с несколькими зачищенными актами — тогда они открываются по очереди. */
async function мДогнать(надо){
  if(мИдёт)return;
  while(МАП.актов<надо){
    const сыграло=await мСыгратьОткрытие();
    if(!сыграло){
      /* За районом ничего нет: показывать нечего, туман над ним и так
         останется. Просто доводим счётчик, чтобы не пытаться снова. */
      МАП.актов=надо; мНарисоватьРайоны(); мНарисоватьДороги();
      break;
    }
  }
  S.mapAct=МАП.актов; save();
}

