/* ================= финал доступного содержимого =================
   Одна дверь, как у входа в бой. Дорог сюда две — кнопка на итогах последнего
   боя и заход на карту с уже пройденным содержимым, — и обе обязаны сперва
   доиграть непрочитанный разговор: «после всех катсцен», а не поверх них. */
function показатьФинал(){
  const дальше=()=>{ S.theEnd=1; save(); go('end') };
  const посл=рейдыАкта(мПоследнийАкт()).slice(-1)[0];
  /* Сначала недочитанный разговор, потом недосмотренные катсцены, и только
     потом «ПРОДОЛЖЕНИЕ СЛЕДУЕТ». Иначе концовка обгоняет то, ради чего игрок
     сюда шёл: акт закрывается кадром из тёмной комнаты, а не экраном итогов. */
  const сцены=()=>{ if(!сценыПодряд(сценыЭтапа('after',посл),дальше))дальше() };
  if(Number.isFinite(посл)&&CHATS[посл]&&CHATS[посл].post&&!chatSeen(посл,'post')
     &&chatNote(посл,'post',сцены))return;
  сцены();
}
