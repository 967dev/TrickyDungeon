/* ================= показ экрана ================= */
/* Слои тумана собираются при первом показе и при изменении размера карты.
   Раньше нельзя: экран скрыт, коробка нулевая. Пересборка ТОЛЬКО по смене
   размера — она перезапускает клубы, и делать её на каждом заходе значит
   каждый раз трогать дым с начала. */
function мСобрать(){
  const карта=мГород();
  const ключ=карта.clientWidth+'x'+карта.clientHeight;
  if(!ключ||ключ==='0x0'||ключ===МАП.собрано)return;
  МАП.собрано=ключ;
  const был=мАктивный;
  мСобратьТуман($('#mapFog')); мСобратьТуман($('#mapFog2'));
  if(!мАктивный){мАктивный=$('#mapFog'); мСпящий=$('#mapFog2')}
  (был||мАктивный).classList.add('on');
}
function renderStages(){
  const надо=мАктовОткрыто();
  /* Показ начинается с того, что игрок УЖЕ видел, и догоняет прогресс
     анимацией. Больше надо быть не может — обрезаем на случай сейва из более
     новой сборки. */
  МАП.актов=Math.min(Math.max(1,S.mapAct||1),надо);
  мСобрать();
  мНарисоватьРайоны();
  мНарисоватьДороги();
  if(мАктивный)мОбновитьПрогалы(мАктивный,МАП.актов);
  /* Табло, открытое до ухода с экрана, показываем снова — но не на район,
     который успел уйти в туман. */
  if(МАП.выбран&&мСост(МАП.выбран,МАП.актов)!=='fog')мОткрытьПанель(МАП.выбран);
  else мЗакрытьПанель();
  /* Финал — ПОСЛЕ догона, а не вместо него: занавес поверх открывающегося
     района съел бы ровно то, ради чего открытие играется. Первая версия стояла
     в else, и на том самом заходе, где игрок закрыл последний акт, финал не
     показывался вовсе — ветка уходила в догон. */
  if(надо>МАП.актов)мДогнать(надо).then(мМожетФинал);
  else мМожетФинал();
}
function мМожетФинал(){
  if(мИдёт||CUR!=='stages')return;
  if(!S.theEnd&&мВсёПройдено())показатьФинал();
}
/* Изменение размера — единственный случай, когда слой тумана можно пересобрать
   целиком: карта всё равно уже перестроилась, и клубы всё равно поедут с новых
   координат. Пересборку решает мСобрать по ключу размера, поэтому здесь просто
   полная отрисовка. */
addEventListener('resize',()=>{ if(CUR==='stages')renderStages() });
